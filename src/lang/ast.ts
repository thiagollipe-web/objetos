export type Expr=Literal|Variable|Binary|Unary|Call|Member|List;
export interface Literal{kind:"literal";value:unknown}
export interface Variable{kind:"variable";name:string}
export interface Binary{kind:"binary";op:string;left:Expr;right:Expr}
export interface Unary{kind:"unary";op:string;expr:Expr}
export interface Call{kind:"call";callee:Expr;args:Expr[]}
export interface Member{kind:"member";object:Expr;property:string}
export interface List{kind:"list";items:Expr[]}
export type Stmt=ExprStmt|Assign|If|While|Repeat|ForEach|FunctionStmt|ReturnStmt|Say|Ask|Break|Draw|ActorStmt|Hook|Noop|Collision;
export interface ExprStmt{kind:"expr";expr:Expr}
export interface Assign{kind:"assign";target:Expr;op:"="|"+="|"-=";value:Expr}
export interface If{kind:"if";condition:Expr;thenBranch:Stmt[];elseBranch:Stmt[]}
export interface While{kind:"while";condition:Expr;body:Stmt[]}
export interface Repeat{kind:"repeat";count:Expr;body:Stmt[]}
export interface ForEach{kind:"foreach";name:string;list:Expr;body:Stmt[]}
export interface FunctionStmt{kind:"function";name:string;params:string[];body:Stmt[]}
export interface ReturnStmt{kind:"return";value?:Expr}
export interface Say{kind:"say";expr:Expr}
export interface Ask{kind:"ask";expr:Expr;name:string}
export interface Break{kind:"break"}
export interface Draw{kind:"draw";shape:string;args:Expr[]}
export interface ActorStmt{kind:"actor";name:string;body:Stmt[]}
export interface Hook{kind:"hook";name:"iniciar"|"atualizar"|"desenhar";body:Stmt[]}
export interface Noop{kind:"noop";name:string;args:Expr[]}
export interface Collision{kind:"collision";a:string;b:string;body:Stmt[]}
export interface Program{gameName:string;body:Stmt[]}